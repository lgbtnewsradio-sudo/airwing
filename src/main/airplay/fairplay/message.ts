const forwardAESSBox: number[] = (() => {
  const table = new Array<number>(256).fill(0);
  for (let encrypted = 0; encrypted < 256; encrypted++) {
    table[inverseAESSBox[encrypted]] = encrypted;
  }
  return table;
})();

function aesGFMultiply(a: number, b: number): number {
  let product = 0;
  a &= 0xff;
  b &= 0xff;
  while (b !== 0) {
    if ((b & 1) !== 0) {
      product ^= a;
    }
    const high = a & 0x80;
    a = (a << 1) & 0xff;
    if (high !== 0) {
      a ^= 0x1b;
    }
    b >>= 1;
  }
  return product & 0xff;
}

function xorAESRoundKey(state: Uint8Array, key: number[]): void {
  for (let i = 0; i < 16; i++) state[i] ^= key[i];
}

function inverseAESShiftRows(state: Uint8Array): void {
  const previous = Uint8Array.from(state);
  for (let row = 0; row < 4; row++) {
    for (let column = 0; column < 4; column++) {
      state[4 * column + row] = previous[4 * ((column - row + 4) & 3) + row];
    }
  }
}

function aesShiftRows(state: Uint8Array): void {
  const previous = Uint8Array.from(state);
  for (let row = 0; row < 4; row++) {
    for (let column = 0; column < 4; column++) {
      state[4 * column + row] = previous[4 * ((column + row) & 3) + row];
    }
  }
}

function inverseAESMixColumns(state: Uint8Array): void {
  for (let column = 0; column < 4; column++) {
    const offset = column * 4;
    const a = state[offset];
    const b = state[offset + 1];
    const c = state[offset + 2];
    const d = state[offset + 3];
    state[offset] =
      aesGFMultiply(a, 14) ^ aesGFMultiply(b, 11) ^ aesGFMultiply(c, 13) ^ aesGFMultiply(d, 9);
    state[offset + 1] =
      aesGFMultiply(a, 9) ^ aesGFMultiply(b, 14) ^ aesGFMultiply(c, 11) ^ aesGFMultiply(d, 13);
    state[offset + 2] =
      aesGFMultiply(a, 13) ^ aesGFMultiply(b, 9) ^ aesGFMultiply(c, 14) ^ aesGFMultiply(d, 11);
    state[offset + 3] =
      aesGFMultiply(a, 11) ^ aesGFMultiply(b, 13) ^ aesGFMultiply(c, 9) ^ aesGFMultiply(d, 14);
  }
}

function aesMixColumns(state: Uint8Array): void {
  for (let column = 0; column < 4; column++) {
    const offset = column * 4;
    const a = state[offset];
    const b = state[offset + 1];
    const c = state[offset + 2];
    const d = state[offset + 3];
    state[offset] = aesGFMultiply(a, 2) ^ aesGFMultiply(b, 3) ^ c ^ d;
    state[offset + 1] = a ^ aesGFMultiply(b, 2) ^ aesGFMultiply(c, 3) ^ d;
    state[offset + 2] = a ^ b ^ aesGFMultiply(c, 2) ^ aesGFMultiply(d, 3);
    state[offset + 3] = aesGFMultiply(a, 3) ^ b ^ c ^ aesGFMultiply(d, 2);
  }
}

function decryptFairPlayMessageBlock(state: Uint8Array, mode: number): void {
  xorAESRoundKey(state, fairplayMessageRoundKey10);
  for (let round = 9; round > 0; round--) {
    inverseAESShiftRows(state);
    for (let i = 0; i < 16; i++) state[i] = inverseAESSBox[state[i]];
    xorAESRoundKey(state, fairplayMessageMiddleKeys[mode][round - 1]);
    inverseAESMixColumns(state);
  }
  inverseAESShiftRows(state);
  for (let i = 0; i < 16; i++) state[i] = inverseAESSBox[state[i]];
  xorAESRoundKey(state, fairplayMessageRoundKey0);
}

function encryptFairPlayMessageBlock(state: Uint8Array, mode: number): void {
  xorAESRoundKey(state, fairplayMessageRoundKey0);
  for (let i = 0; i < 16; i++) state[i] = forwardAESSBox[state[i]];
  aesShiftRows(state);
  for (let round = 0; round < 9; round++) {
    aesMixColumns(state);
    xorAESRoundKey(state, fairplayMessageMiddleKeys[mode][round]);
    for (let i = 0; i < 16; i++) state[i] = forwardAESSBox[state[i]];
    aesShiftRows(state);
  }
  xorAESRoundKey(state, fairplayMessageRoundKey10);
}

// decryptFairPlayMessage decrypts the 128-byte body at message[16:144] into
// plaintext[0:128]. `message` must be at least 144 bytes; message[12] is the mode.
export function decryptFairPlayMessage(message: Uint8Array, plaintext: Uint8Array): void {
  const mode = message[12];
  for (let step = 0; step < 8; step++) {
    let block = step;
    if (mode === 3) {
      // Mode 3 historically traverses the CBC chain backwards.
      block = 7 - step;
    }
    const start = 16 + block * 16;
    const state = new Uint8Array(16);
    state.set(message.subarray(start, start + 16));
    decryptFairPlayMessageBlock(state, mode);

    let chain: Uint8Array | number[];
    if (block > 0) {
      chain = message.subarray(start - 16, start);
    } else {
      chain = fairplayMessageIV[mode];
    }
    for (let i = 0; i < 16; i++) {
      plaintext[block * 16 + i] = state[i] ^ chain[i];
    }
  }
}

// encryptFairPlayMessage applies the inverse of decryptFairPlayMessage to one
// 128-byte SAP value, writing the encrypted body into `encrypted` (128 bytes).
export function encryptFairPlayMessage(
  mode: number,
  plaintext: Uint8Array,
  encrypted: Uint8Array,
): void {
  if (mode >= fairplayMessageIV.length) {
    throw new Error(`unsupported FairPlay mode ${mode}`);
  }
  if (plaintext.length !== 128 || encrypted.length !== 128) {
    throw new Error(
      `FairPlay message body lengths are ${plaintext.length} and ${encrypted.length}, want 128`,
    );
  }

  let chain: Uint8Array | number[] = fairplayMessageIV[mode];
  for (let block = 0; block < 8; block++) {
    const start = block * 16;
    const state = new Uint8Array(16);
    for (let i = 0; i < 16; i++) {
      state[i] = plaintext[start + i] ^ chain[i];
    }
    encryptFairPlayMessageBlock(state, mode);
    encrypted.set(state, start);
    chain = encrypted.subarray(start, start + 16);
  }
}
